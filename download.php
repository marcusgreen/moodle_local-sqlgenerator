require_once(__DIR__ . '/../../config.php');
require_once($CFG->dirroot . '/local/sqlgenerator/locallib.php');

require_admin();

// PARAM_FILE strips any directory components, so only files directly in the output dir can be requested.
$file = required_param('file', PARAM_FILE);
$allowed = ['sql', 'properties'];
if (!in_array(pathinfo($file, PATHINFO_EXTENSION), $allowed, true)) {
    throw new moodle_exception('invalidparameter', 'debug');
}

$path = local_sqlgenerator_output_dir() . '/' . $file;
if (!is_readable($path)) {
    throw new moodle_exception('filenotfound', 'error');
}

send_file($path, $file, 0, 0, false, true, 'text/plain');
